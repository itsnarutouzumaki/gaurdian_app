void i18n.use(initReactI18next).init({
  resources: {
    en: { translation: {} },
    hi: { translation: hindi },
  },
  lng: "en",
  fallbackLng: "en",
  interpolation: { escapeValue: false },
  initAsync: false,
});

export { i18n };

export function translate(text: string, language: Language): string {
  if (language === "en") return text;
  const normalized = text.replace(/\s+/g, " ").trim();
  const key = i18n.exists(text, { lng: language })
    ? text
    : i18n.exists(normalized, { lng: language })
      ? normalized
      : null;
  const exact = key ? i18n.t(key, { lng: language }) : undefined;
  if (exact) return exact;

  const unreadCount = /^(\d+) unread update(s?)$/.exec(normalized);
  if (unreadCount) {
    const count = new Intl.NumberFormat("hi-IN").format(Number(unreadCount[1]));
    return `${count} अपठित अपडेट`;
  }
  const unreadNotifications = /^(\d+) unread notifications$/.exec(normalized);
  if (unreadNotifications) {
    const count = new Intl.NumberFormat("hi-IN").format(
      Number(unreadNotifications[1]),
    );
    return `${count} अपठित सूचनाएँ`;
  }

  const pdfCreated = /^A demo PDF was created at:\s*(.+)$/.exec(normalized);
  if (pdfCreated) return `डेमो PDF यहाँ बनाई गई है: ${pdfCreated[1]}`;
  const monthYear = /^([A-Za-z]+) (\d{4})$/.exec(normalized);
  if (monthYear) {
    const localizedMonth = i18n.t(monthYear[1], { lng: language });
    if (localizedMonth !== monthYear[1]) {
      return `${localizedMonth} ${monthYear[2]}`;
    }
  }

  const studentId = /^Student ID:\s*(.+)$/.exec(normalized);
  if (studentId) return `विद्यार्थी ID: ${studentId[1]}`;

  const className = /^Class (\d+)$/.exec(normalized);
  if (className) return `कक्षा ${className[1]}`;

  const section = /^(.+) · Section$/.exec(normalized);
  if (section) return `${section[1]} · अनुभाग`;

  const schoolLabel = /^School:\s*(.+)$/.exec(normalized);
  if (schoolLabel) return `स्कूल: ${schoolLabel[1]}`;

  const alreadyLinked = /^(.+) is already visible in My Children\.$/.exec(normalized);
  if (alreadyLinked) {
    return `${alreadyLinked[1]} पहले से मेरे बच्चों में दिखाई दे रहे हैं।`;
  }

  const studentRequest = /^Your request for (.+) is waiting for principal approval\.$/.exec(normalized);
  if (studentRequest) {
    return `${studentRequest[1]} के लिए आपका अनुरोध प्रधानाचार्य की स्वीकृति की प्रतीक्षा कर रहा है।`;
  }

  const missingFields = /^Please complete these required fields: (.+)\. If mobile or email is missing, contact the school office\.$/.exec(normalized);
  if (missingFields) {
    return `कृपया यह आवश्यक जानकारी पूरी करें: ${missingFields[1]}। मोबाइल या ईमेल उपलब्ध न हो तो स्कूल कार्यालय से संपर्क करें।`;
  }

  return text;
}
